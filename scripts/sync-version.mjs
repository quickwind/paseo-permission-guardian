#!/usr/bin/env node
// Writes shared/version.ts from package.json. Paseo bundles plugin code and only accepts modules
// under client/, server/ or shared/, so package.json cannot be imported at runtime. Runs on
// `npm version` (see the "version" script); a unit test fails if the two drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
if (typeof version !== "string" || !version) throw new Error("package.json has no version");
const out = `// Generated by scripts/sync-version.mjs from package.json. Do not edit by hand.\nexport const PLUGIN_VERSION = ${JSON.stringify(version)};\n`;
writeFileSync(join(root, "shared", "version.ts"), out);
console.log(`shared/version.ts -> ${version}`);
